// Generates the gallery pages (index.html plus one page per category) from sections.json and the
// snippet files under sections/. Plain Node, no dependencies: `node build.mjs`.
//
// The snippet files are the single source of truth. Each one is shown twice on its page, as a live
// preview (inside an iframe, so the Desktop/Tablet/Mobile switch triggers real breakpoints) and as
// copyable code, and both come from the same file, so they can't drift apart. The add-section skill
// in BootForm/site-skills fetches the same files. Run this after editing anything under sections/
// and commit the regenerated pages; CI fails if they're stale.
import { readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(fileURLToPath(import.meta.url))
const manifest = JSON.parse(readFileSync(join(root, 'sections.json'), 'utf-8'))

const escapeHtml = (value) =>
  String(value).replace(/[&<>"]/g, (char) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[char])

// Must match the brand tokens every BootForm VitePress template defines, so a snippet that looks
// right here looks right there. Only 50, 500 and 600 exist there; snippets use nothing else.
const THEME = `@custom-variant dark (&:where(.dark, .dark *));
  @theme {
    --color-brand-50: #eef2ff;
    --color-brand-500: #4f46e5;
    --color-brand-600: #4338ca;
  }`

const TAILWIND = 'https://cdn.jsdelivr.net/npm/@tailwindcss/browser@4'

function previewDocument(snippet) {
  return `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<script src="${TAILWIND}"></script><style type="text/tailwindcss">${THEME}</style>
<script>if (parent.document.documentElement.classList.contains('dark')) document.documentElement.classList.add('dark')</script>
</head><body class="bg-white text-neutral-900 antialiased dark:bg-neutral-950 dark:text-neutral-100">${snippet}</body></html>`
}

function page({ title, description, body, current }) {
  const nav = manifest.categories
    .map((c) => `<a href="${c.id}.html" class="whitespace-nowrap hover:text-brand-600${c.id === current ? ' text-brand-600' : ''}">${escapeHtml(c.title)}</a>`)
    .join('\n        ')
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${escapeHtml(title)}</title>
<meta name="description" content="${escapeHtml(description)}">
<!-- Generated by build.mjs from sections.json and sections/. Don't edit this file by hand. -->
<script src="${TAILWIND}"></script>
<style type="text/tailwindcss">
  ${THEME}
</style>
<script>
  try { if (localStorage.getItem('theme') === 'dark') document.documentElement.classList.add('dark') } catch {}
</script>
<link href="https://cdn.jsdelivr.net/npm/prismjs@1.29.0/themes/prism-tomorrow.min.css" rel="stylesheet">
<style>
  pre[class*="language-"] { margin: 0; border-radius: 0; font-size: 0.8125rem; max-height: 32rem; }
</style>
</head>
<body class="bg-neutral-50 text-neutral-900 antialiased dark:bg-neutral-900 dark:text-neutral-100">
<nav class="sticky top-0 z-10 border-b border-black/10 bg-neutral-50/90 backdrop-blur dark:border-white/10 dark:bg-neutral-900/90">
  <div class="mx-auto flex max-w-6xl flex-wrap items-center justify-between gap-x-6 gap-y-2 px-6 py-4">
    <a href="index.html" class="font-bold tracking-tight">site-sections</a>
    <div class="flex flex-wrap items-center gap-x-5 gap-y-2 text-sm font-medium">
        ${nav}
      <a href="https://github.com/BootForm/site-sections" class="hover:text-brand-600">GitHub</a>
      <button id="theme-toggle" type="button" aria-label="Toggle dark mode" class="rounded-md border border-black/10 px-2 py-1 text-xs dark:border-white/20">
        <span class="dark:hidden">Dark</span><span class="hidden dark:inline">Light</span>
      </button>
    </div>
  </div>
</nav>
${body}
<footer class="border-t border-black/10 px-6 py-8 text-center text-sm text-black/50 dark:border-white/10 dark:text-white/50">
  Built by <a href="https://bootform.com" class="underline">BootForm</a>. Part of
  <a href="https://github.com/BootForm" class="underline">github.com/BootForm</a>: free templates, and a working contact form for whatever you build.
</footer>
<script src="https://cdn.jsdelivr.net/npm/prismjs@1.29.0/prism.min.js"></script>
<script>
  // Dark mode: flip .dark on this page and on every preview iframe.
  const frames = () => document.querySelectorAll('iframe[data-preview]')
  document.getElementById('theme-toggle').addEventListener('click', () => {
    const dark = document.documentElement.classList.toggle('dark')
    try { localStorage.setItem('theme', dark ? 'dark' : 'light') } catch {}
    frames().forEach((f) => f.contentDocument?.documentElement.classList.toggle('dark', dark))
  })

  // Each preview iframe grows to fit its content, so there's never a scrollbar inside a preview.
  function fit(frame) {
    const doc = frame.contentDocument
    if (doc?.body) frame.style.height = doc.documentElement.scrollHeight + 'px'
  }
  frames().forEach((frame) => {
    frame.addEventListener('load', () => {
      fit(frame)
      new ResizeObserver(() => fit(frame)).observe(frame.contentDocument.body)
      frame.contentDocument.addEventListener('click', (e) => { if (e.target.closest('a[href="#"]')) e.preventDefault() })
    })
  })

  // Desktop / Tablet / Mobile: changes the iframe's width, which is what media queries respond to.
  document.querySelectorAll('[data-width]').forEach((button) => {
    button.addEventListener('click', () => {
      const box = button.closest('section')
      box.querySelector('iframe').style.width = button.dataset.width
      box.querySelectorAll('[data-width]').forEach((b) => b.setAttribute('aria-pressed', String(b === button)))
    })
  })

  // Hand-rolled copy button: Prism's own plugin relies on document.execCommand('copy'), which
  // current Chrome refuses. See form-styles' AGENTS.md.
  document.querySelectorAll('.copy-btn').forEach((button) => {
    button.addEventListener('click', async () => {
      const code = button.closest('section').querySelector('code').textContent
      try {
        await navigator.clipboard.writeText(code)
        button.textContent = 'Copied!'
      } catch {
        button.textContent = 'Press Ctrl+C'
      }
      setTimeout(() => (button.textContent = 'Copy'), 1500)
    })
  })
</script>
</body>
</html>
`
}

const widthButton = (label, width, pressed) =>
  `<button type="button" data-width="${width}" aria-pressed="${pressed}" class="rounded px-2.5 py-1 text-xs font-medium aria-pressed:bg-brand-500 aria-pressed:text-white">${label}</button>`

function sectionBlock(category, section) {
  const snippet = readFileSync(join(root, 'sections', category.id, `${section.id}.html`), 'utf-8').replace(/\r\n/g, '\n').trimEnd()
  const notes = section.notes?.length
    ? `<ul class="mt-3 list-disc space-y-1 pl-5 text-sm text-black/60 dark:text-white/60">${section.notes.map((n) => `<li>${n}</li>`).join('')}</ul>`
    : ''
  return `
  <section id="${section.id}" class="scroll-mt-24 border-b border-black/10 py-12 first:pt-0 last:border-0 dark:border-white/10">
    <div class="flex flex-wrap items-baseline justify-between gap-2">
      <h2 class="text-xl font-bold tracking-tight"><a href="#${section.id}" class="hover:text-brand-600">${escapeHtml(section.title)}</a></h2>
      <code class="text-xs text-black/50 dark:text-white/50">sections/${category.id}/${section.id}.html</code>
    </div>
    <p class="mt-2 max-w-3xl text-sm leading-relaxed text-black/70 dark:text-white/70">${section.description}</p>
    ${notes}
    <div class="mt-5 overflow-hidden rounded-xl border border-black/10 dark:border-white/10">
      <div class="flex items-center justify-between gap-2 border-b border-black/10 bg-white px-3 py-2 dark:border-white/10 dark:bg-white/5">
        <div class="flex gap-1" role="group" aria-label="Preview width">
          ${widthButton('Desktop', '100%', true)}
          ${widthButton('Tablet', '768px', false)}
          ${widthButton('Mobile', '390px', false)}
        </div>
      </div>
      <div class="overflow-x-auto bg-neutral-200 dark:bg-black/40">
        <iframe data-preview title="${escapeHtml(section.title)} preview" loading="lazy" srcdoc="${escapeHtml(previewDocument(snippet))}" class="mx-auto block h-96 w-full max-w-full bg-white transition-[width] dark:bg-neutral-950"></iframe>
      </div>
      <div class="relative">
        <button type="button" class="copy-btn absolute right-3 top-3 z-10 rounded border border-white/20 bg-white/10 px-2 py-1 text-xs font-medium text-white hover:bg-white/20">Copy</button>
        <pre><code class="language-markup">${escapeHtml(snippet)}</code></pre>
      </div>
    </div>
  </section>`
}

let total = 0
for (const category of manifest.categories) {
  total += category.sections.length
  const body = `<main class="mx-auto max-w-6xl px-6 py-12">
  <h1 class="text-3xl font-bold tracking-tight">${escapeHtml(category.title)}</h1>
  <p class="mt-3 max-w-3xl text-black/70 dark:text-white/70">${category.description}</p>
  <p class="mt-4 flex flex-wrap gap-x-4 gap-y-1 text-sm">${category.sections.map((s) => `<a href="#${s.id}" class="text-brand-600 hover:underline">${escapeHtml(s.title)}</a>`).join('')}</p>
  <div class="mt-10">${category.sections.map((s) => sectionBlock(category, s)).join('\n')}
  </div>
</main>`
  writeFileSync(
    join(root, `${category.id}.html`),
    page({ title: `${category.title}: site-sections`, description: category.description.replace(/<[^>]+>/g, ''), body, current: category.id }),
  )
}

const cards = manifest.categories
  .map(
    (c) => `
    <a href="${c.id}.html" class="group rounded-xl border border-black/10 bg-white p-6 transition hover:border-brand-500 dark:border-white/10 dark:bg-white/5">
      <h2 class="text-lg font-bold group-hover:text-brand-600">${escapeHtml(c.title)} <span class="text-sm font-normal text-black/50 dark:text-white/50">${c.sections.length}</span></h2>
      <p class="mt-2 text-sm text-black/70 dark:text-white/70">${c.sections.map((s) => escapeHtml(s.title)).join(', ')}.</p>
    </a>`,
  )
  .join('')

const indexBody = `<main>
  <div class="mx-auto max-w-3xl px-6 py-20 text-center">
    <h1 class="text-4xl font-bold tracking-tight sm:text-5xl">Page sections you can paste</h1>
    <p class="mx-auto mt-4 max-w-xl text-lg text-black/70 dark:text-white/70">${manifest.intro}</p>
    <p class="mt-3 text-sm text-black/50 dark:text-white/50">${total} sections. Tailwind CSS v4, light and dark, every one checked at desktop and phone widths.</p>
  </div>
  <div class="mx-auto grid max-w-6xl gap-6 px-6 pb-16 sm:grid-cols-2 lg:grid-cols-3">${cards}
  </div>
  <div class="mx-auto max-w-3xl px-6 pb-20">
    <div class="rounded-xl border border-black/10 bg-brand-50 p-6 text-sm leading-relaxed dark:border-white/10 dark:bg-brand-500/10">
      <h2 class="text-base font-bold">Before you paste one</h2>
      ${manifest.beforeYouPaste}
    </div>
  </div>
</main>`
writeFileSync(join(root, 'index.html'), page({ title: 'site-sections: page sections you can paste', description: manifest.description, body: indexBody, current: '' }))

console.log(`Built index.html and ${manifest.categories.length} category pages, ${total} sections.`)
